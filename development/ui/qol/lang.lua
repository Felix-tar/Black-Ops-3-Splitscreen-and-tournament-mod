-- Translations for every text this mod shows. English is the default and the
-- master list: a key missing in another language falls back to English.
--
-- QoL.L("key", a, b) replaces the placeholders {1}, {2} in the text.
-- The language is picked in the game settings (input.lua adds the row), kept
-- in the profile store (record "L", data.lua) and in the session dvar
-- qol_lang so the match HUD uses it too.
--
-- Note: the game's own fonts may not contain Chinese or Devanagari glyphs.
-- Those languages are offered, but text can stay blank on such installs.
require("ui.qol.util")

local QoL = CoD.QoL
local Lang = {}
QoL.lang = Lang

local DVAR = "qol_lang"
Lang.DEFAULT = "en"
Lang.ORDER = { "en", "de", "es", "pt", "zh", "hi" }
-- Latin names only: the selector has to stay readable even when the game has
-- no font for that language.
Lang.NAMES = {
    en = "English",
    de = "Deutsch (German)",
    es = "Espanol (Spanish)",
    pt = "Portugues (Portuguese)",
    zh = "Chinese - needs a Chinese font",
    hi = "Hindi - needs a Hindi font"
}

-- Engine.GetLanguage() -> our code, for the automatic first choice.
local GAME_LANGUAGE = {
    english = "en",
    german = "de",
    spanish = "es",
    mexicanspanish = "es",
    latinamericanspanish = "es",
    portuguese = "pt",
    brazilianportuguese = "pt",
    simplifiedchinese = "zh",
    traditionalchinese = "zh",
    chinese = "zh",
    hindi = "hi"
}

-- Language of the game itself, or nil when we have no translation for it.
function Lang.detect()
    local ok, name = pcall(Engine.GetLanguage)
    if ok and type(name) == "string" then
        return GAME_LANGUAGE[string.lower(name)]
    end
    return nil
end

