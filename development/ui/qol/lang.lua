-- Lookup -------------------------------------------------------------------------

local CACHE = nil
-- Counts changes so open menus can notice and redraw (splitlobby.lua).
Lang.version = 0

-- Chosen language: what the player picked (session dvar or profile store),
-- otherwise the language of the game, otherwise English.
function Lang.current()
    if CACHE then
        return CACHE
    end
    local code = QoL.getSessionValue(DVAR)
    if not Lang.strings[code] and QoL.data then
        local ok, state = pcall(QoL.data.get)
        if ok and state and Lang.strings[state.language] then
            code = state.language
        end
    end
    if not Lang.strings[code] then
        code = Lang.detect() or Lang.DEFAULT
    end
    CACHE = code
    return code
end

-- Forgets the cached choice (e.g. after the profile store was read) and lets
-- menus redraw if the language turns out to be a different one.
function Lang.reset()
    local previous = CACHE
    CACHE = nil
    if previous ~= Lang.current() then
        Lang.version = Lang.version + 1
    end
end

function Lang.set(code)
    if not Lang.strings[code] then
        code = Lang.DEFAULT
    end
    if CACHE ~= code then
        Lang.version = Lang.version + 1
    end
    CACHE = code
    QoL.setSessionValue(DVAR, code)
    if QoL.data then
        QoL.safe("lang.save", function()
            local state = QoL.data.get()
            if state.language ~= code then
                state.language = code
                QoL.data.save()
            end
        end)
    end
    -- Lists that were built in the old language have to be rebuilt.
    QoL.safe("lang.rebuildLobby", function()
        if LuaUtils and LuaUtils.ForceLobbyButtonUpdate then
            LuaUtils.ForceLobbyButtonUpdate()
        end
    end)
    QoL.log("language: " .. code)
end

-- Text for `key` in the current language, English as fallback; {1}, {2} are
-- replaced by the extra arguments.
function QoL.L(key, ...)
    local table1 = Lang.strings[Lang.current()] or Lang.strings.en
    local text = table1[key] or Lang.strings.en[key]
    if not text then
        return tostring(key)
    end
    local count = select("#", ...)
    if count == 0 then
        return text
    end
    local args = { ... }
    return (string.gsub(text, "{(%d)}", function(index)
        local value = args[tonumber(index)]
        return value ~= nil and tostring(value) or ""
    end))
end

-- Keys missing in a language (self-test).
function Lang.missing(code)
    local missing = {}
    local other = Lang.strings[code] or {}
    for key in pairs(Lang.strings.en) do
        if other[key] == nil then
            table.insert(missing, key)
        end
    end
    return missing
end
